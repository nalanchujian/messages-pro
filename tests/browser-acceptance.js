// Playwright CLI snippet: run with `playwright-cli run-code --filename tests/browser-acceptance.js`.
// It uses an isolated browser session and clears only that session's local storage.
async (page) => {
  const passed = []
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  const verify = async (label, locator, expected) => {
    const actual = (await locator.textContent())?.replace(/\s+/g, ' ').trim() ?? ''
    if (!actual.replace(/\s+/g, '').includes(expected.replace(/\s+/g, ''))) throw new Error(`${label}: expected “${expected}”, got “${actual}”`)
    passed.push(label)
  }
  const queue = (name) => page.getByRole('group', { name: '行动队列' }).getByRole('button', { name: new RegExp(`^${name} `) })
  const insights = page.getByRole('complementary', { name: '会话洞察' })

  await page.setViewportSize({ width: 1440, height: 900 })
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await verify('初始待履约队列', queue('待履约'), '待履约 1')

  await page.getByRole('button', { name: /^R Riley/ }).click()
  await verify('初始已付款状态', insights.locator('.workflow-facts'), '付款：已记录')
  await verify('初始待核对状态', insights.locator('.workflow-facts'), '交付：待核对')
  await page.getByRole('textbox', { name: '回复 Riley' }).fill('我先核对订单和交付安排，确认后回复你。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await verify('发送后仍待履约', queue('待履约'), '待履约 1')
  await verify('发送与交付分离', insights.locator('.workflow-facts'), '回复：已发送')
  await verify('发送后仍待核对', insights.locator('.workflow-facts'), '交付：待核对')

  await page.getByRole('region', { name: '聊天模块' }).getByRole('region', { name: '当前行动操作' }).getByRole('button', { name: '请求团队核对' }).click()
  await verify('核对中仍在待履约队列', queue('待履约'), '待履约 1')
  await verify('三栏核对状态同步', insights.locator('.workflow-facts'), '交付：团队核对中')
  await page.screenshot({ path: 'output/playwright/stage1-reviewing.png', fullPage: true })

  await insights.getByRole('button', { name: /^切换演示租户/ }).click()
  await page.getByRole('button', { name: 'North Agency 规模效率型' }).click()
  await verify('North 租户保留独立样例', queue('待履约'), '待履约 4')
  await page.getByRole('button', { name: 'Aster Studio 精品关系型' }).click()
  await page.getByRole('button', { name: '关闭租户切换弹窗' }).click()
  await page.getByRole('button', { name: /^R Riley/ }).click()
  await verify('切回 Aster 恢复核对状态', insights.locator('.workflow-facts'), '交付：团队核对中')

  await page.reload()
  await page.getByRole('button', { name: /^R Riley/ }).click()
  await verify('刷新后保留核对状态', insights.locator('.workflow-facts'), '交付：团队核对中')
  await page.getByRole('region', { name: '聊天模块' }).getByRole('region', { name: '当前行动操作' }).getByRole('button', { name: '确认已交付' }).click()
  await verify('确认后移出待履约队列', queue('待履约'), '待履约 0')
  await verify('交付状态已确认', insights.locator('.workflow-facts'), '交付：已确认')
  await verify('事实区更新交付结果', insights, '已由操作员确认交付')
  if ((await insights.textContent())?.includes('尚未确认具体时间')) throw new Error('交付完成后仍显示过期的交付时间备注')
  passed.push('完成后无过期交付备注')
  await page.screenshot({ path: 'output/playwright/stage1-delivered.png', fullPage: true })

  await page.getByRole('button', { name: /^L Leo Carter/ }).click()
  await verify('购买已记录', insights.locator('.workflow-facts'), 'PPV：已购买')
  await page.getByRole('textbox', { name: '回复 Leo Carter' }).fill('谢谢喜欢这组照片！你最喜欢哪一张？')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await verify('购买与回复状态分离', insights.locator('.workflow-facts'), 'PPV：已购买')
  await verify('购买后回复已发送', insights.locator('.workflow-facts'), '回复：已发送')
  await verify('跟进移入等待状态', queue('购买跟进'), '购买跟进 0')

  await page.getByRole('button', { name: /^M Mason/ }).click()
  const chat = page.getByRole('region', { name: '聊天模块' })
  const sentBefore = await chat.locator('.message-row.outbound').count()
  await chat.getByRole('region', { name: '当前行动操作' }).getByRole('button', { name: '生成回复' }).click()
  await chat.getByRole('button', { name: '插入', exact: true }).first().click()
  if (await chat.locator('.message-row.outbound').count() !== sentBefore) throw new Error('AI 草稿未经人工发送就进入聊天记录')
  if (!(await page.getByRole('textbox', { name: '回复 Mason' }).inputValue()).trim()) throw new Error('AI 草稿未插入输入框')
  passed.push('AI 草稿仅插入输入框')
  await chat.getByRole('button', { name: '发送', exact: true }).click()
  if (await chat.locator('.message-row.outbound').count() !== sentBefore + 1) throw new Error('人工发送后消息未进入聊天记录')
  await verify('日常回复转入等待', insights.locator('.workflow-facts'), '回复：已发送')

  await page.getByRole('complementary', { name: '用户列表' }).getByRole('button', { name: /^工作台设置/ }).click()
  await page.getByRole('tab', { name: '手动微调' }).click()
  await page.locator('.queue-choice').filter({ hasText: '人工判断' }).locator('input').uncheck()
  await page.getByRole('button', { name: '完成', exact: true }).click()
  if (await page.getByRole('group', { name: '行动队列' }).locator('.queue-button').count() !== 5) throw new Error('手动队列设置未生效')
  passed.push('Aster 手动配置即时生效')

  const switchTenant = async (name) => {
    await insights.getByRole('button', { name: /^切换演示租户/ }).click()
    await page.getByRole('button', { name }).click()
    await page.getByRole('button', { name: '关闭租户切换弹窗' }).click()
  }
  await switchTenant('North Agency 规模效率型')
  if (await page.getByRole('group', { name: '行动队列' }).locator('.queue-button').count() !== 6) throw new Error('Aster 手动队列设置泄漏至 North')
  passed.push('租户手动配置隔离')
  await verify('North 默认履约会话', page.getByRole('region', { name: '聊天模块' }).locator('.chat-identity'), 'Riley')
  const selectedInView = await page.evaluate(() => {
    const list = document.querySelector('.conversation-list')?.getBoundingClientRect()
    const selected = document.querySelector('.conversation.selected')?.getBoundingClientRect()
    return Boolean(list && selected && selected.top >= list.top && selected.bottom <= list.bottom)
  })
  if (!selectedInView) throw new Error('切换租户后当前会话未出现在左侧可视区域')
  passed.push('North 当前会话可见')
  await verify('North 高并发处理工具', page.getByRole('complementary', { name: '用户列表' }).locator('.load-action-bar'), '待处理')
  await verify('North 轮班交接', insights.locator('.collaboration-panel'), '轮班交接')
  await page.screenshot({ path: 'output/playwright/tenant-north.png' })
  if (!await page.getByRole('complementary', { name: '用户列表' }).getByRole('button', { name: /^待交接/ }).isVisible()) throw new Error('North 缺少交接筛选')
  passed.push('North 交接筛选')

  await switchTenant('Pulse House 增长转化型')
  await verify('Pulse 默认购买会话', page.getByRole('region', { name: '聊天模块' }).locator('.chat-identity'), 'Leo Carter')
  await verify('Pulse 首要队列', page.getByRole('group', { name: '行动队列' }).locator('.queue-button').nth(1), '购买跟进')
  await verify('Pulse 购买洞察', insights.locator('.tenant-insight-brief'), '购买与互动')
  await page.screenshot({ path: 'output/playwright/tenant-pulse.png' })

  await switchTenant('Seed Club 冷启动带教型')
  await verify('Seed 默认日常会话', page.getByRole('region', { name: '聊天模块' }).locator('.chat-identity'), 'Nate Wilson')
  await verify('Seed 资料核对入口', insights.locator('.coverage-warning'), '资料覆盖率')
  if (await insights.locator('.collaboration-panel').count()) throw new Error('专人负责租户显示了团队协作面板')
  passed.push('Seed 专人模式')
  await page.getByRole('button', { name: '核对助手' }).click()
  await page.getByRole('button', { name: '回复', exact: true }).click()
  if (!await page.getByRole('button', { name: '插入', exact: true }).first().isDisabled()) throw new Error('资料不足时 AI 草稿未被拦截')
  passed.push('Seed AI 草稿核对门槛')
  await insights.getByRole('button', { name: '确认已核对' }).click()
  if (await page.getByRole('button', { name: '插入', exact: true }).first().isDisabled()) throw new Error('核对后 AI 草稿仍被拦截')
  passed.push('Seed 核对后可用草稿')
  await page.getByRole('textbox', { name: '回复 Nate Wilson' }).fill('Seed 独立草稿')
  await page.screenshot({ path: 'output/playwright/tenant-seed.png' })

  await insights.getByRole('button', { name: /^切换演示租户/ }).click()
  await page.getByRole('button', { name: '自定义租户 自由组合六个维度' }).click()
  await page.getByRole('group', { name: '日均会话负载' }).getByRole('button', { name: '高负载' }).click()
  await page.getByRole('group', { name: '主导会话类型' }).getByRole('button', { name: '服务履约' }).click()
  await page.getByRole('group', { name: '粉丝资料完备度' }).getByRole('button', { name: '较低' }).click()
  await page.getByRole('group', { name: '会话协作模式' }).getByRole('button', { name: '轮班交接' }).click()
  await page.getByRole('button', { name: '关闭租户切换弹窗' }).click()
  await verify('组合租户仍优先待履约', page.getByRole('group', { name: '行动队列' }).locator('.queue-button').nth(1), '待履约')
  await verify('组合租户资料核对', insights.locator('.coverage-warning'), '资料覆盖率')
  await verify('组合租户轮班交接', insights.locator('.collaboration-panel'), '轮班交接')
  if (await page.getByRole('complementary', { name: '用户列表' }).locator('.queue-button').count() > 6) throw new Error('行动队列超过 6 个')
  passed.push('组合租户队列上限')
  await page.getByRole('button', { name: /^O Oliver Reed/ }).click()
  await page.getByRole('textbox', { name: '回复 Oliver Reed' }).fill('切换负载后仍应保留')
  await chat.getByRole('button', { name: '发送', exact: true }).click()
  await insights.getByRole('button', { name: /^切换演示租户/ }).click()
  await page.getByRole('group', { name: '日均会话负载' }).getByRole('button', { name: '低负载' }).click()
  await page.getByRole('button', { name: '关闭租户切换弹窗' }).click()
  if (await page.getByRole('button', { name: /^O Oliver Reed/ }).count()) throw new Error('低负载仍显示高负载会话')
  passed.push('低负载收起部分会话')
  await insights.getByRole('button', { name: /^切换演示租户/ }).click()
  await page.getByRole('group', { name: '日均会话负载' }).getByRole('button', { name: '高负载' }).click()
  await page.getByRole('button', { name: '关闭租户切换弹窗' }).click()
  await page.getByRole('button', { name: /^O Oliver Reed/ }).click()
  await verify('恢复高负载后保留隐藏会话消息', chat.locator('.message-thread'), '切换负载后仍应保留')
  await page.reload()
  await verify('组合租户刷新后保留', insights.locator('.collaboration-panel'), '轮班交接')
  await switchTenant('Seed Club 冷启动带教型')
  if (await page.getByRole('textbox', { name: '回复 Nate Wilson' }).inputValue() !== 'Seed 独立草稿') throw new Error('Seed 草稿未按租户保留')
  passed.push('租户草稿隔离')
  await switchTenant('自定义租户 自由组合六个维度')

  for (const width of [1920, 1440, 1280, 800]) {
    await page.setViewportSize({ width, height: 900 })
    await page.reload()
    const layout = await page.evaluate(() => {
      const app = document.querySelector('.app-shell')
      const chat = document.querySelector('.chat-panel')
      const detail = document.querySelector('.detail-panel')
      return { documentWidth: document.documentElement.scrollWidth, appHeight: app?.getBoundingClientRect().height,
        inboxHeaderCount: document.querySelectorAll('.inbox-header').length,
        chatWidth: chat?.getBoundingClientRect().width, detailVisible: detail && getComputedStyle(detail).display !== 'none' }
    })
    if (layout.documentWidth > width + 1 || layout.appHeight !== 900 || layout.inboxHeaderCount !== 1 || !layout.chatWidth || layout.chatWidth < 300) throw new Error(`${width}px 布局异常：${JSON.stringify(layout)}`)
    if (layout.detailVisible !== (width > 1000)) throw new Error(`${width}px 侧栏断点异常`)
    passed.push(`${width}px 全屏布局`)
    await page.screenshot({ path: `output/playwright/responsive-${width}.png` })
  }
  await page.getByRole('button', { name: '会话洞察', exact: true }).click()
  if (!await insights.isVisible()) throw new Error('窄屏无法打开会话洞察')
  await insights.getByRole('button', { name: '关闭会话洞察' }).click()
  passed.push('窄屏洞察抽屉')
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.reload()
  await switchTenant('Aster Studio 精品关系型')
  if (await page.getByRole('group', { name: '行动队列' }).locator('.queue-button').count() !== 5) throw new Error('切回 Aster 后手动配置未保留')
  passed.push('Aster 手动配置切回后保留')

  await page.evaluate(() => {
    localStorage.removeItem('messages-pro-session-v1:aster')
    localStorage.setItem('messages-pro-drafts:aster', JSON.stringify({ mason: '旧版草稿已迁移' }))
    localStorage.setItem('messages-pro-action-statuses:aster', JSON.stringify({ riley: 'waiting' }))
  })
  await page.reload()
  await page.getByRole('button', { name: /^M Mason/ }).click()
  if (await page.getByRole('textbox', { name: '回复 Mason' }).inputValue() !== '旧版草稿已迁移') throw new Error('旧版租户草稿未迁移')
  passed.push('旧版草稿迁移')
  await page.getByRole('button', { name: /^R Riley/ }).click()
  await verify('旧版行动状态迁移', insights.locator('.workflow-facts'), '交付：团队核对中')
  if (errors.length) throw new Error(`浏览器脚本错误：${errors.join('; ')}`)
  return { result: 'PASS', checks: passed.length, passed, screenshots: ['output/playwright/stage1-reviewing.png', 'output/playwright/stage1-delivered.png', 'output/playwright/tenant-north.png', 'output/playwright/tenant-pulse.png', 'output/playwright/tenant-seed.png', ...[1920, 1440, 1280, 800].map((width) => `output/playwright/responsive-${width}.png`)] }
}
